package oOOps;

public class methodOverloading {

	public int sum(int a, int b) {
		return a+b;
	}
	public int sum(int a, int b,int c) {
		return a+b+c;
	}
	public int sum(int a, int b,int c,int d) {
		return a+b+c+d;
	}
	public Float sum(Float a, Float b,Float c,Float d,Float e) {
		return a+b+c+d+e;
	}
	
}
